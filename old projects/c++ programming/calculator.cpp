#include <iostream>
using namespace std;
int main(int argc, char const *argv[])
{
    int num1,num2;
    cout<<"\nEnter the first number : ";
    cin>>num1;
    cout<<"Enter the second number : ";
    cin>>num2;
    cout<<"\nThe sum of the two numbers you entered is : "<<num1+num2;
    cout<<"\nThe subtraction of the two numbers you entered is : "<<num1-num2;
    cout<<"\nThe product of the two numbers you entered is : "<<num1*num2;
    cout<<"\nThe division of the two numbers you entered is : "<<num1/num2;
    return 0;
}
